    function translateKey(key, fallback = '') {
        if (!key) return fallback;
        const dict = LUMINA_TRANSLATIONS[currentLang] || LUMINA_TRANSLATIONS.pl;
        const resolvedKey = KEY_ALIASES[key] || key.replace(/\./g, '_');

        // 1. Sprawdź dokładny klucz lub zmapowany alias w bieżącym języku
        if (dict) {
            if (dict[key] !== undefined) return dict[key];
            if (dict[resolvedKey] !== undefined) return dict[resolvedKey];
        }

        // 2. Fallback do słownika polskiego
        if (LUMINA_TRANSLATIONS.pl) {
            if (LUMINA_TRANSLATIONS.pl[key] !== undefined) return LUMINA_TRANSLATIONS.pl[key];
            if (LUMINA_TRANSLATIONS.pl[resolvedKey] !== undefined) return LUMINA_TRANSLATIONS.pl[resolvedKey];
        }
        return fallback || key;
    }

    // ── 2. Aplikowanie tłumaczeń do drzewa DOM ──
    function applyTranslations(rootEl = document) {
        if (!rootEl || !rootEl.querySelectorAll) return;

        // Tekst elementu: [data-i18n]
        const textElements = rootEl.querySelectorAll('[data-i18n]');
        textElements.forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (!key) return;
            const text = translateKey(key);
            if (text) {
                // Jeśli element ma ikony wewnętrzne, szukamy tekstu lub zastępujemy span
                const labelSpan = el.querySelector('.nav-btn-text, .btn-nav-cta-text, .tab-label, span.i18n-label, span:not(.fa-solid):not(.fa-brands)');
                if (labelSpan) {
                    labelSpan.textContent = text;
                } else if (el.childNodes.length === 1 && el.childNodes[0].nodeType === 3) {
                    el.textContent = text;
                } else {
                    // Sprawdzamy czy element zawiera ikony font-awesome
                    const icon = el.querySelector('i');
                    if (icon) {
                        const cloneIcon = icon.cloneNode(true);
                        el.innerHTML = '';
                        el.appendChild(cloneIcon);
                        el.appendChild(document.createTextNode(' ' + text));
                    } else {
                        el.textContent = text;
                    }
                }
            }
        });

        // Tytuły i podpowiedzi: [data-i18n-title]
        const titleElements = rootEl.querySelectorAll('[data-i18n-title]');
        titleElements.forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            if (!key) return;
            const text = translateKey(key);
            if (text) el.setAttribute('title', text);
        });

        // Placeholdery formularzy: [data-i18n-placeholder]
        const placeholderElements = rootEl.querySelectorAll('[data-i18n-placeholder]');
        placeholderElements.forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (!key) return;
            const text = translateKey(key);
            if (text) el.setAttribute('placeholder', text);
        });

        // Etykiety dostępności: [data-i18n-aria-label]
        const ariaElements = rootEl.querySelectorAll('[data-i18n-aria-label]');
        ariaElements.forEach(el => {
            const key = el.getAttribute('data-i18n-aria-label');
            if (!key) return;
            const text = translateKey(key);
            if (text) el.setAttribute('aria-label', text);
        });
    }


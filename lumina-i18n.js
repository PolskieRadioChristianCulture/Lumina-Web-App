    global.setLuminaLanguage = setLanguage;
    global.setLanguage = setLanguage;
    global.changeLanguage = setLanguage;

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init);
    } else {
        init();
    }


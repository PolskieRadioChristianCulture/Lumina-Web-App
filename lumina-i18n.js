    global.LuminaI18n = {
        init: init,
        getLang: () => currentLang,
        setLang: setLanguage,
        toggle: toggleLanguage,
        t: translateKey,
        apply: applyTranslations,
        ensureSwitcher: ensureLanguageSwitcher,
        translations: LUMINA_TRANSLATIONS
    };


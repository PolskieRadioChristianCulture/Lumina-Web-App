/**
 * Mapowanie nazw grup WhatsApp na kategorie tematyczne
 */
export function mapGroupToCategory(groupName = '') {
  const n = groupName.toLowerCase();
  if (n.includes('rodzic') || n.includes('mama') || n.includes('dom') || n.includes('rodzina')) return 'rodzina';
  if (n.includes('zdrow') || n.includes('ciało')) return 'zdrowie';
  if (n.includes('biznes') || n.includes('praca') || n.includes('firma')) return 'biznes';
  if (n.includes('kobieta') || n.includes('kobiet')) return 'kobiety';
  if (n.includes('mężczyzna') || n.includes('mezczyzn') || n.includes('mężczyzn')) return 'mezczyzni';
  if (n.includes('singiel') || n.includes('samotn')) return 'single';
  if (n.includes('worship') || n.includes('muzyka') || n.includes('chwała')) return 'worship';
  if (n.includes('modlit') || n.includes('pomodlę') || n.includes('pomogę') || n.includes('cuda') || n.includes('zwyciężamy')) return 'modlitwa';
  if (n.includes('bibli') || n.includes('studium') || n.includes('werset') || n.includes('kazania') || n.includes('teologia') || n.includes('wiar')) return 'studium';
  return 'ogolne';
}

